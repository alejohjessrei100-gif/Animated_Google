// Packs ./public into src/assets.gen.js so the Worker can serve the game without
// the separate static-assets upload API. Run automatically by `npm run build`.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");
const TYPES = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".json": "application/json", ".mp3": "audio/mpeg", ".png": "image/png", ".svg": "image/svg+xml", ".ico": "image/x-icon", ".txt": "text/plain; charset=utf-8" };
const out = {};
const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else { const ext = extname(n); if (!TYPES[ext]) continue; const buf = readFileSync(p); out["/" + relative(pub, p).split("\\").join("/")] = { t: TYPES[ext], e: createHash("sha1").update(buf).digest("hex").slice(0, 16), b: buf.toString("base64") }; } } };
walk(pub);
writeFileSync(join(root, "src/assets.gen.js"), "// generated by tools/build-assets.mjs — do not edit\nexport default " + JSON.stringify(out) + ";\n");
console.log(`packed ${Object.keys(out).length} files, ${(Object.values(out).reduce((a, f) => a + f.b.length, 0) / 1024).toFixed(0)} KB base64`);
